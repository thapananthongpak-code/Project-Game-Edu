// เหลือเฉพาะการอ่านบันทึกเดิม (shop.dash) เพื่อให้เครดิตที่ผู้เล่นเคยได้จากด่านนี้ยังนับเหมือนเดิม เครดิตคงเหลือจึงไม่ติดลบ

export const DASH = {
  /** เครดิตที่ได้เมื่อผ่านด่านครั้งแรก (ข้ามไม่ได้เครดิต) */
  reward: 5,
} as const;

/** รหัสในบันทึกเดิม: "<แมพ>:<ห้อง>" = ผ่านแล้ว, "<แมพ>:<ห้อง>:s" = ข้าม, "skip" = ตั้งค่าข้ามทุกด่าน */
export const DASH_ENTRY = /^(?:(?:easy|normal|hard):\d{1,2}(?::s)?|skip)$/;

/** เครดิตจากด่านที่เคยผ่าน (นับจากจำนวนรหัสที่ผ่านแล้วเสมอ ไม่เก็บยอดสะสม) */
export const dashCredits = (done: readonly string[]): number => done.filter((entry) => /^(?:easy|normal|hard):\d{1,2}$/.test(entry)).length * DASH.reward;
